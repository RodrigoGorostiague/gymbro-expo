export function getShopTheme(id: string): ShopTheme | undefined {
  return PROFILE_THEMES.find((theme) => theme.id === id) ?? SHOP_THEMES.find((theme) => theme.id === id);
}

export function getAllShopThemes(): ShopTheme[] {
  return [...PROFILE_THEMES, ...SHOP_THEMES];
}

export function getThemesByCategory(category: ShopThemeCategory): ShopTheme[] {
  return getAllShopThemes().filter((theme) => theme.category === category);
}
